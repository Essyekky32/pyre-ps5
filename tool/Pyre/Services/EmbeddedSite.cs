using System.IO;
using System.IO.Compression;
using System.Reflection;
using System.Security.Cryptography;
using System.Text.Json;
using Pyre.Server;

namespace Pyre.Services;

/// <summary>Where the bytes being served come from.</summary>
public enum SiteSourceKind
{
    /// <summary>The copy carried inside Pyre.exe, unpacked and hash-verified.</summary>
    Embedded,

    /// <summary>An explicit --root folder the user asked for (development/testing).</summary>
    Override,
}

public enum SiteErrorKind
{
    None,

    /// <summary>The embedded copy failed to unpack or verify against its manifest.</summary>
    EmbeddedFailed,

    /// <summary>--root was given and there is no index.html in it.</summary>
    OverrideMissing,
}

public sealed class SiteManifestFile
{
    public string Path { get; set; } = string.Empty;

    public long Size { get; set; }

    public string Sha256 { get; set; } = string.Empty;
}

/// <summary>
/// Build-time generated by <c>tool\build-embed.ps1</c> and embedded as
/// <c>Pyre.Site.site-manifest.json</c>: every file carried inside the exe, with its SHA256.
/// The runtime verifies each file against this while unpacking, and again before serving -
/// so the bytes the console receives are the bytes that were packed.
/// </summary>
public sealed class SiteManifest
{
    public int Schema { get; set; }

    public string BuildId { get; set; } = string.Empty;

    public string GeneratedUtc { get; set; } = string.Empty;

    public bool IncludeOptionalPayloads { get; set; }

    public int FileCount { get; set; }

    public long TotalBytes { get; set; }

    public string ZipSha256 { get; set; } = string.Empty;

    public long ZipSize { get; set; }

    public List<SiteManifestFile> Files { get; set; } = new();

    /// <summary>
    /// The ELF payloads this build expects to sit BESIDE Pyre.exe (wave 4 stopped packing
    /// them inside it). The runtime never unpacks these - it resolves them next to itself and
    /// reports which are present and which are missing. Empty for a pre-wave-4 build.
    /// </summary>
    public List<SiteManifestPayload> Payloads { get; set; } = new();
}

public sealed class SiteResolution
{
    public bool Ok { get; set; }

    public SiteSourceKind Kind { get; set; } = SiteSourceKind.Embedded;

    public string Root { get; set; } = string.Empty;

    public string BuildId { get; set; } = string.Empty;

    public int FileCount { get; set; }

    public long TotalBytes { get; set; }

    /// <summary>True for the embedded copy: it was unpacked and SHA256-verified.</summary>
    public bool Verified { get; set; }

    public SiteErrorKind ErrorKind { get; set; } = SiteErrorKind.None;

    public string Error { get; set; } = string.Empty;
}

/// <summary>
/// The site Pyre.exe carries inside itself.
///
/// Wave 1 served whatever folder the exe sat in and refused to start without index.html
/// next to it - a folder dependency, and the thing that broke for a user who just wanted
/// one file. Wave 2 packs the whole site into the exe at build time (a deterministic zip
/// plus a SHA256 manifest, both embedded), unpacks it to
/// <c>%LOCALAPPDATA%\Pyre\site\&lt;buildId&gt;\</c> on first use, verifies every byte
/// against the manifest while it writes, and serves from there. If verification fails,
/// nothing is served: that is the point of the check.
///
/// Wave 4 keeps the pages, scripts, styles, offsets and licence files embedded, but the ELF
/// payloads now ship BESIDE the exe (see <see cref="ElfLocator"/>) - they are too big to want
/// inside a "one small file" download, and keeping them outside lets Cam drop a new build in
/// without repacking the exe. The manifest lists them (path/size/sha256/optional) so the GUI
/// and the selftest can say plainly which are present and which are missing.
/// </summary>
internal static class EmbeddedSite
{
    public const string ZipResourceName = "Pyre.Site.site.zip";
    public const string ManifestResourceName = "Pyre.Site.site-manifest.json";

    private static readonly JsonSerializerOptions JsonOptions = new()
    {
        PropertyNameCaseInsensitive = true,
    };

    // One unpacker at a time: two Pyre instances starting together would otherwise race
    // over the same "%LOCALAPPDATA%\Pyre\site\<buildId>" folder.
    private static readonly Mutex ExtractGate = new(false, @"Local\PyreSiteExtract");

    private static SiteManifest? _manifest;
    private static string _manifestError = string.Empty;

    /// <summary>
    /// Resolve what to serve. <paramref name="overrideRoot"/> is the --root value: when it
    /// is given, that folder is served deliberately (development/testing) and the embedded
    /// copy is not touched. When it is null, the embedded copy is unpacked and verified.
    /// </summary>
    public static SiteResolution Resolve(string? overrideRoot)
    {
        if (!string.IsNullOrWhiteSpace(overrideRoot))
        {
            string root;
            try
            {
                root = Path.GetFullPath(overrideRoot);
            }
            catch (Exception ex)
            {
                return new SiteResolution
                {
                    Ok = false,
                    Kind = SiteSourceKind.Override,
                    Root = overrideRoot,
                    ErrorKind = SiteErrorKind.OverrideMissing,
                    Error = $"{overrideRoot} is not a usable path: {ex.Message}",
                };
            }

            if (!PyreWebServer.LooksLikeSite(root))
            {
                return new SiteResolution
                {
                    Ok = false,
                    Kind = SiteSourceKind.Override,
                    Root = root,
                    ErrorKind = SiteErrorKind.OverrideMissing,
                    Error = $"no index.html in {root}",
                };
            }

            return new SiteResolution
            {
                Ok = true,
                Kind = SiteSourceKind.Override,
                Root = root,
                Verified = false,
            };
        }

        return EnsureEmbedded();
    }

    private static SiteResolution EnsureEmbedded()
    {
        var manifest = LoadManifest(out var error);
        if (manifest is null)
        {
            return new SiteResolution
            {
                Ok = false,
                Kind = SiteSourceKind.Embedded,
                ErrorKind = SiteErrorKind.EmbeddedFailed,
                Error = error,
            };
        }

        string target;
        try
        {
            target = AppPaths.EmbeddedSiteDirectory(manifest.BuildId);
        }
        catch (Exception ex)
        {
            return Failed(manifest, ex.Message);
        }

        // Already unpacked and every byte still matches the manifest: nothing to do.
        if (VerifyExtracted(target, manifest, out _, out _))
        {
            return Ok(manifest, target);
        }

        ExtractGate.WaitOne();
        try
        {
            // Another instance may have finished while we waited for the mutex.
            if (VerifyExtracted(target, manifest, out _, out _))
            {
                return Ok(manifest, target);
            }

            var temp = target + ".tmp-" + Guid.NewGuid().ToString("N");
            try
            {
                Directory.CreateDirectory(AppPaths.SiteRootDirectory);
                ExtractAndVerify(temp, manifest);
            }
            catch (Exception ex)
            {
                TryDeleteDirectory(temp);
                return Failed(manifest, ex.Message);
            }

            try
            {
                TryDeleteDirectory(target);
                Directory.Move(temp, target);
            }
            catch (Exception ex)
            {
                TryDeleteDirectory(temp);

                // The old copy is still good (a file was locked): use it rather than fail.
                if (VerifyExtracted(target, manifest, out _, out _))
                {
                    return Ok(manifest, target);
                }

                return Failed(manifest, "could not put the unpacked site in place: " + ex.Message);
            }

            return Ok(manifest, target);
        }
        finally
        {
            ExtractGate.ReleaseMutex();
        }
    }

    /// <summary>The embedded manifest, or null plus a reason it could not be read.</summary>
    public static SiteManifest? LoadManifest(out string error)
    {
        if (_manifest is not null)
        {
            error = string.Empty;
            return _manifest;
        }

        if (_manifestError.Length > 0)
        {
            error = _manifestError;
            return null;
        }

        try
        {
            using var stream = typeof(EmbeddedSite).Assembly.GetManifestResourceStream(ManifestResourceName);
            if (stream is null)
            {
                _manifestError = $"this build has no embedded {ManifestResourceName}";
                error = _manifestError;
                return null;
            }

            var manifest = JsonSerializer.Deserialize<SiteManifest>(stream, JsonOptions);
            if (manifest is null || manifest.Files.Count == 0 || manifest.BuildId.Length == 0)
            {
                _manifestError = "the embedded site manifest is empty or unreadable";
                error = _manifestError;
                return null;
            }

            _manifest = manifest;
            error = string.Empty;
            return manifest;
        }
        catch (Exception ex)
        {
            _manifestError = $"{ex.GetType().Name}: {ex.Message}";
            error = _manifestError;
            return null;
        }
    }

    /// <summary>
    /// SHA256 every file in <paramref name="root"/> against the manifest. This is the check
    /// that proves the bytes on disk are the bytes that were packed.
    /// </summary>
    public static bool VerifyExtracted(string root, SiteManifest manifest, out int mismatches, out string firstProblem)
    {
        mismatches = 0;
        firstProblem = string.Empty;

        if (!Directory.Exists(root))
        {
            mismatches = manifest.Files.Count;
            firstProblem = $"{root} does not exist";
            return false;
        }

        foreach (var file in manifest.Files)
        {
            string path;
            try
            {
                path = SafeDestination(root, file.Path);
            }
            catch (Exception ex)
            {
                mismatches++;
                if (firstProblem.Length == 0) firstProblem = ex.Message;
                continue;
            }

            try
            {
                var info = new FileInfo(path);
                if (!info.Exists)
                {
                    mismatches++;
                    if (firstProblem.Length == 0) firstProblem = $"{file.Path} is missing";
                    continue;
                }

                if (info.Length != file.Size)
                {
                    mismatches++;
                    if (firstProblem.Length == 0) firstProblem = $"{file.Path} is {info.Length} bytes, manifest says {file.Size}";
                    continue;
                }

                using var stream = File.OpenRead(path);
                var hash = Convert.ToHexString(SHA256.HashData(stream));
                if (!hash.Equals(file.Sha256, StringComparison.OrdinalIgnoreCase))
                {
                    mismatches++;
                    if (firstProblem.Length == 0) firstProblem = $"{file.Path} does not match the manifest sha256";
                }
            }
            catch (Exception ex)
            {
                mismatches++;
                if (firstProblem.Length == 0) firstProblem = $"{file.Path}: {ex.GetType().Name}: {ex.Message}";
            }
        }

        return mismatches == 0;
    }

    /// <summary>
    /// Unpack the embedded zip into <paramref name="destination"/>, hashing every file while
    /// it is written. A single mismatch aborts: nothing half-verified is ever served.
    /// </summary>
    private static void ExtractAndVerify(string destination, SiteManifest manifest)
    {
        using var raw = typeof(EmbeddedSite).Assembly.GetManifestResourceStream(ZipResourceName)
            ?? throw new InvalidDataException($"this build has no embedded {ZipResourceName}");

        using var zip = new ZipArchive(raw, ZipArchiveMode.Read);

        var entries = new Dictionary<string, ZipArchiveEntry>(StringComparer.Ordinal);
        foreach (var entry in zip.Entries)
        {
            // Directory entries are not part of the manifest.
            if (entry.FullName.EndsWith('/') || entry.FullName.EndsWith('\\'))
            {
                continue;
            }

            entries[entry.FullName] = entry;
        }

        if (entries.Count != manifest.Files.Count)
        {
            throw new InvalidDataException(
                $"the embedded zip holds {entries.Count} files but the manifest lists {manifest.Files.Count}");
        }

        Directory.CreateDirectory(destination);

        var buffer = new byte[64 * 1024];

        foreach (var file in manifest.Files)
        {
            if (!entries.TryGetValue(file.Path, out var entry))
            {
                throw new InvalidDataException($"the embedded zip is missing {file.Path}");
            }

            var target = SafeDestination(destination, file.Path);
            var parent = Path.GetDirectoryName(target);
            if (!string.IsNullOrEmpty(parent))
            {
                Directory.CreateDirectory(parent);
            }

            long written = 0;
            string hash;

            using (var source = entry.Open())
            using (var output = new FileStream(target, FileMode.Create, FileAccess.Write, FileShare.None, buffer.Length))
            using (var sha = SHA256.Create())
            {
                int read;
                while ((read = source.Read(buffer, 0, buffer.Length)) > 0)
                {
                    output.Write(buffer, 0, read);
                    sha.TransformBlock(buffer, 0, read, null, 0);
                    written += read;
                }

                sha.TransformFinalBlock(Array.Empty<byte>(), 0, 0);
                hash = Convert.ToHexString(sha.Hash!);
            }

            if (written != file.Size)
            {
                throw new InvalidDataException($"{file.Path}: unpacked {written} bytes, manifest says {file.Size}");
            }

            if (!hash.Equals(file.Sha256, StringComparison.OrdinalIgnoreCase))
            {
                throw new InvalidDataException($"{file.Path}: unpacked sha256 {hash} does not match the manifest ({file.Sha256})");
            }
        }
    }

    /// <summary>Manifest entry -> a path, refusing anything that tries to escape the root.</summary>
    private static string SafeDestination(string root, string relative)
    {
        if (string.IsNullOrWhiteSpace(relative) || Path.IsPathRooted(relative) || relative.Contains(':'))
        {
            throw new InvalidDataException($"unsafe path in the site manifest: {relative}");
        }

        var segments = relative.Split('/', '\\');
        if (segments.Any(s => s.Length == 0 || s == "." || s == ".."))
        {
            throw new InvalidDataException($"unsafe path in the site manifest: {relative}");
        }

        var full = Path.GetFullPath(Path.Combine(root, Path.Combine(segments)));
        var prefix = root.EndsWith(Path.DirectorySeparatorChar) ? root : root + Path.DirectorySeparatorChar;
        if (!full.StartsWith(prefix, StringComparison.OrdinalIgnoreCase))
        {
            throw new InvalidDataException($"unsafe path in the site manifest: {relative}");
        }

        return full;
    }

    /// <summary>
    /// The autoloader SOURCE zip under <c>our-payloads\</c> is never needed at runtime and
    /// must not ship in any build. (The autoloader installer ELF itself DOES ship - a page
    /// pushes it to the console - so it is not an offender.)
    /// </summary>
    private static bool IsRuntimeSourceZip(string relative) =>
        relative.StartsWith("our-payloads/", StringComparison.OrdinalIgnoreCase) &&
        relative.EndsWith(".zip", StringComparison.OrdinalIgnoreCase);

    /// <summary>
    /// Wave 4: the ELF payloads ship BESIDE the exe, never inside it. A build that embedded an
    /// <c>.elf</c> again would double-serve it (and quietly break the "drop it anywhere, it
    /// looks next to itself" rule), and no build may carry the autoloader source zip. This
    /// fails loudly if either ever sneaks back in.
    /// </summary>
    public static bool ManifestCarriesNoElfs(SiteManifest manifest, out string detail)
    {
        detail = string.Empty;

        var offenders = manifest.Files
            .Select(f => f.Path)
            .Where(p => p.EndsWith(".elf", StringComparison.OrdinalIgnoreCase) || IsRuntimeSourceZip(p))
            .ToList();

        if (offenders.Count == 0)
        {
            detail = $"the embedded site carries no payload binaries ({manifest.Payloads.Count} ship beside the exe)";
            return true;
        }

        detail = string.Join(", ", offenders.Take(5));
        return false;
    }

    /// <summary>Is <paramref name="relativePath"/> in the set the build expects beside the exe?</summary>
    public static bool ManifestExpectsPayload(SiteManifest manifest, string relativePath, out SiteManifestPayload? payload)
    {
        payload = manifest.Payloads.FirstOrDefault(
            p => string.Equals(p.Path, relativePath, StringComparison.OrdinalIgnoreCase));
        return payload is not null;
    }

    private static SiteResolution Ok(SiteManifest manifest, string root) => new()
    {
        Ok = true,
        Kind = SiteSourceKind.Embedded,
        Root = root,
        BuildId = manifest.BuildId,
        FileCount = manifest.Files.Count,
        TotalBytes = manifest.TotalBytes,
        Verified = true,
    };

    private static SiteResolution Failed(SiteManifest manifest, string error) => new()
    {
        Ok = false,
        Kind = SiteSourceKind.Embedded,
        BuildId = manifest.BuildId,
        FileCount = manifest.Files.Count,
        TotalBytes = manifest.TotalBytes,
        ErrorKind = SiteErrorKind.EmbeddedFailed,
        Error = error,
    };

    private static void TryDeleteDirectory(string path)
    {
        try
        {
            if (Directory.Exists(path))
            {
                Directory.Delete(path, recursive: true);
            }
        }
        catch (Exception)
        {
            // a leftover temp folder is not worth failing a launch for
        }
    }
}
