# Regenerate the two generated payload files, from what is on disk.
#
#   haze-catalog-data.js     what the Additional Payloads buttons push
#   payload-sources.json     the provenance list linked from a page
#   _FROZEN-MANIFEST.txt     refreshed for the amended frozen file
#
# Run this after ANY change to the payload set. haze-sender.js verifies each
# file against the sha256 here before pushing, so a stale value makes Pyre refuse
# to send the payload - that is exactly what this script exists to prevent.
#
# Layout it expects:
#   payloads/      the RUN PYRE chain (names fixed by frozen site code)
#   our-payloads/  everything we ship ourselves
$ErrorActionPreference = 'Stop'
$PYRE = 'D:\Projects\PYRE'
function Hash([string]$p) { (Get-FileHash $p -Algorithm SHA256).Hash.ToLower() }

$entries = @(
  @{ id='manager';         title='PYRE Payloads';        ver='0.6.1-pyre';      file='our-payloads/pyre-payloads_pldmgr_v0.6.1-pyre.elf'; auth='Essy (based on itsPLK)'; src='https://github.com/itsPLK/ps5-payload-manager'; desc='Dashboard to manage, import and auto-load payloads. PYRE build: v0.6.1 base, re-themed, renamed, install-from-list removed - upload payloads directly.' },
  @{ id='dumper';          title='PS5 App Dumper';       ver='2.00';            file='our-payloads/ps5-app-dumper_v2.00.elf';             auth='EchoStretch'; src='https://github.com/EchoStretch/ps5-app-dumper/releases/tag/v2.00'; desc='Dump installed apps and games to USB storage. Starts automatically with RUN PYRE, with automatic dumping left off.' },
  @{ id='omnipad';         title='OmniPad';              ver='1.0.4-g7pro-b98'; file='our-payloads/OmniPad-PS5-1.0.4-g7pro-b98.elf';      auth='Essy (fork)';            src='https://github.com/saawant12/orbit-store-ps5';   desc='USB controller payload. Verified working with the GameSir G7 Pro, GameSir G7 SE and Nintendo Switch Pro controllers on 13.60.' },
  @{ id='cheatrunner';     title='CheatRunner';          ver='0.17.2';          file='our-payloads/CheatRunner_v0.17.2.elf';              auth=''; src=''; desc='Cheat engine front-end for PS5.' },
  @{ id='pkg-manager';     title='PKG-Manager';          ver='1.4.1';           file='our-payloads/PKG-Manager_v1.4.1.elf';               auth=''; src=''; desc='Install and manage PKG files.' },
  @{ id='web-file-manager';title='PS5 Web File Manager'; ver='1.9';             file='our-payloads/ps5-web-file-manager_v1.9.elf';        auth=''; src=''; desc='Browse and move files on the console over HTTP.' },
  @{ id='ftpsrv';          title='ftpsrv';               ver='0.21.1';          file='our-payloads/ftpsrv_v0.21.1.elf';                   auth='drakmor'; src='https://github.com/drakmor/ftpsrv';  desc='FTP server on port 2121, anonymous. What everything else is pushed through.' },
  @{ id='nanodns';         title='nanoDNS';              ver='0.4';             file='our-payloads/nanodns.elf';                          auth='drakmor'; src='https://github.com/drakmor/nanoDNS'; desc='Local DNS proxy. Blocks Sony, and with AdGuard/ControlD upstreams blocks ad and tracker networks.' },
  @{ id='np-fake-signin';  title='np-fake-signin';       ver='';                file='our-payloads/np-fake-signin-ps5.elf';               auth=''; src=''; desc='Spoofs PSN sign-in so the console stops nagging.' },
  @{ id='kstuff';          title='kstuff';               ver='1.11';            file='payloads/kstuff.elf';                               auth=''; src=''; desc='Kernel patch payload used by the RUN PYRE chain. Also pushable on its own from here.' },
  @{ id='shadowmount';     title='ShadowMountPlus';      ver='1.7beta3';        file='payloads/shadowmountplus.elf';                      auth='drakmor'; src=''; desc='Mounts game backups. Used by the RUN PYRE chain.' },
  @{ id='etahen';          title='etaHEN';               ver='13.60';           file='payloads/etaHEN.elf';                               auth=''; src=''; desc='The homebrew enabler, built for firmware 13.60. Used by the RUN PYRE chain.' }
)

Write-Output "=== haze-catalog-data.js ==="
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("// Pinned payloads; automatic services first.")
[void]$sb.AppendLine("//")
[void]$sb.AppendLine("// GENERATED by tool/regen_payload_files.ps1 - do not hand-edit sha256/bytes.")
[void]$sb.AppendLine("// haze-sender.js verifies each file against these values before pushing, so a")
[void]$sb.AppendLine("// mismatch makes Pyre REFUSE to send the payload.")
[void]$sb.AppendLine("export const payloads = [")
for ($i = 0; $i -lt $entries.Count; $i++) {
  $e = $entries[$i]
  $p = Join-Path $PYRE ($e.file -replace '/', '\')
  if (-not (Test-Path $p)) { throw "catalogue entry points at a missing file: $($e.file)" }
  [void]$sb.AppendLine("  {")
  [void]$sb.AppendLine(('    "id": "{0}",' -f $e.id))
  [void]$sb.AppendLine(('    "title": "{0}",' -f $e.title))
  [void]$sb.AppendLine(('    "version": "{0}",' -f $e.ver))
  [void]$sb.AppendLine(('    "file": "{0}",' -f $e.file))
  [void]$sb.AppendLine(('    "sha256": "{0}",' -f (Hash $p)))
  [void]$sb.AppendLine(('    "bytes": {0},' -f (Get-Item $p).Length))
  [void]$sb.AppendLine(('    "description": "{0}",' -f $e.desc))
  [void]$sb.AppendLine(('    "author": "{0}",' -f $e.auth))
  [void]$sb.AppendLine(('    "source": "{0}",' -f $e.src))
  [void]$sb.AppendLine('    "loaderOnly": false,')
  [void]$sb.AppendLine($(if ($i -eq $entries.Count - 1) { '    "repeatable": false' } else { '    "repeatable": false' }))
  [void]$sb.AppendLine($(if ($i -eq $entries.Count - 1) { '  }' } else { '  },' }))
  Write-Output ("  {0,-16} {1,-48} {2,10:N0} B" -f $e.id, $e.file, (Get-Item $p).Length)
}
[void]$sb.AppendLine("];")
Set-Content -Path (Join-Path $PYRE 'haze-catalog-data.js') -Value $sb.ToString() -Encoding UTF8 -NoNewline

Write-Output ""
Write-Output "=== payload-sources.json ==="
$list = @()
foreach ($e in $entries) {
  $p = Join-Path $PYRE ($e.file -replace '/', '\')
  $list += [ordered]@{
    name = (Split-Path $p -Leaf); title = $e.title; description = $e.desc
    original = (Split-Path $p -Leaf); author = $e.auth; repository = $e.src
    download = ''; version = $e.ver; fw = $null; id = $e.id
    bytes = (Get-Item $p).Length; sha256 = (Hash $p)
    source = $e.src; sourceArchive = ''; loaderOnly = $false; repeatable = $false
  }
}
Set-Content -Path (Join-Path $PYRE 'payload-sources.json') -Value ($list | ConvertTo-Json -Depth 5) -Encoding UTF8
Write-Output ("  {0} entries" -f $list.Count)

Write-Output ""
Write-Output "=== _FROZEN-MANIFEST.txt ==="
$m = Join-Path $PYRE '_FROZEN-MANIFEST.txt'
$new = (Hash (Join-Path $PYRE 'haze-catalog-data.js')).ToUpper()
$lines = Get-Content $m
$hit = $false
for ($i = 0; $i -lt $lines.Count; $i++) {
  if ($lines[$i] -match 'haze-catalog-data\.js') { $lines[$i] = "$new  haze-catalog-data.js"; $hit = $true }
}
if (-not $hit) { throw "haze-catalog-data.js not present in the frozen manifest" }
Set-Content -Path $m -Value $lines -Encoding UTF8
Write-Output ("  haze-catalog-data.js -> {0}" -f $new)
